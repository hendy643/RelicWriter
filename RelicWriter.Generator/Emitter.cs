using System.Text;
using System.Text.RegularExpressions;

namespace RelicWriter.Generator;

/// <summary>
/// Emits one record class and one INodeCodec per node. Spec conditions are translated to C#: v is the save version, a the archive version,
/// any other identifier is an earlier field of the same node (or of the enclosing struct).
/// shortcut: an array whose count is named by countField writes no count of its own, so editing that array's length also needs the count field changed; revisit if such arrays become editable.
/// </summary>
sealed partial class Emitter(string buildLabel)
{
    static readonly Dictionary<string, (string Cs, string Read, string Write)> Prim = new()
    {
        ["u8"] = ("byte", "r.U8()", "w.U8({0})"),
        ["u16"] = ("ushort", "r.U16()", "w.U16({0})"),
        ["u32"] = ("uint", "r.U32()", "w.U32({0})"),
        ["u64"] = ("ulong", "r.U64()", "w.U64({0})"),
        ["i32"] = ("int", "r.I32()", "w.I32({0})"),
        ["f32"] = ("float", "r.F32()", "w.F32({0})"),
        ["string"] = ("string", "r.String()", "w.String({0})"),
        ["name"] = ("string", "r.String()", "w.String({0})"),
    };

    sealed class Block
    {
        public readonly StringBuilder Props = new();
        public readonly StringBuilder Read = new();
        public readonly StringBuilder Write = new();
    }

    /// <summary>Spec field name to the C# local (read side) and property expression (write side).</summary>
    sealed record Names(Dictionary<string, (string Read, string Write)> Map);

    public static string TypeName(string node) =>
        string.Concat(Regex.Split(node, "[^A-Za-z0-9]+").Where(p => p.Length > 0).Select(p => char.ToUpperInvariant(p[0]) + p[1..]));

    static string Prop(string name, HashSet<string> used, string owner)
    {
        var p = TypeName(name);
        if (p.Length == 0 || char.IsDigit(p[0])) p = "F" + p;
        if (p == owner) p += "Value";
        var baseName = p;
        for (var i = 2; !used.Add(p); i++) p = baseName + i;
        return p;
    }

    public string Emit(NodeSpec node)
    {
        var type = TypeName(node.Name);
        var b = new Block();
        Members(node.Fields, type, type, b, [], 0, "        ", "value");

        var sb = new StringBuilder();
        sb.Append($"// <auto-generated> from save-spec.xml (game build {buildLabel}). Do not edit; run RelicWriter.Generator. </auto-generated>\n");
        sb.Append("namespace RelicWriter.Common.Codecs.Generated;\n\n");
        sb.Append($"/// <summary>Node {node.Name.Replace("\"", "&quot;")} (spec status: {node.Status}).</summary>\n");
        sb.Append($"public sealed class {type}\n{{\n{b.Props}}}\n\n");
        sb.Append($"public sealed class {type}Codec : INodeCodec<{type}>\n{{\n");
        sb.Append($"    public const string Node = \"{node.Name.Replace("\"", "\\\"")}\";\n\n");
        sb.Append($"    public {type} Read(ReadOnlySpan<byte> data, SaveContext ctx)\n    {{\n");
        sb.Append("        var r = new NodeReader(data);\n        var v = ctx.SaveVersion;\n        var a = ctx.ArchiveVersion;\n        _ = v; _ = a;\n");
        sb.Append($"        var value = new {type}();\n");
        sb.Append(b.Read);
        sb.Append("        if (r.Remaining != 0) throw new InvalidDataException($\"{Node}: {r.Remaining} bytes left after reading\");\n        return value;\n    }\n\n");
        sb.Append($"    public byte[] Write({type} value, SaveContext ctx)\n    {{\n");
        sb.Append("        var w = new NodeWriter();\n        var v = ctx.SaveVersion;\n        var a = ctx.ArchiveVersion;\n        _ = v; _ = a;\n");
        sb.Append(b.Write);
        sb.Append("        return w.ToArray();\n    }\n}\n");
        return sb.ToString();
    }

    public string EmitRegistry(IEnumerable<NodeSpec> nodes)
    {
        var sb = new StringBuilder();
        sb.Append($"// <auto-generated> from save-spec.xml (game build {buildLabel}). Do not edit; run RelicWriter.Generator. </auto-generated>\n");
        sb.Append("namespace RelicWriter.Common.Codecs.Generated;\n\n");
        sb.Append("public static class GeneratedCodecs\n{\n");
        sb.Append("    /// <summary>Per node name: read then write a payload (used to check that the codec reproduces the original bytes).</summary>\n");
        sb.Append("    public static readonly IReadOnlyDictionary<string, Func<byte[], SaveContext, byte[]>> RoundTrips = new Dictionary<string, Func<byte[], SaveContext, byte[]>>\n    {\n");
        foreach (var n in nodes)
        {
            var t = TypeName(n.Name);
            sb.Append($"        [{t}Codec.Node] = (data, ctx) => {{ var c = new {t}Codec(); return c.Write(c.Read(data, ctx), ctx); }},\n");
        }
        sb.Append("    };\n}\n");
        return sb.ToString();
    }

    void Members(List<Field> fields, string owner, string typePath, Block b, Dictionary<string, (string Read, string Write)> outer, int depth, string ind, string obj)
    {
        var used = new HashSet<string>();
        var props = fields.Select(f => Prop(f.Name, used, owner)).ToList();
        var locals = props.Select(p => $"l{depth}_{p}").ToList();
        var names = new Dictionary<string, (string, string)>(outer);
        for (var i = 0; i < fields.Count; i++) names[fields[i].Name] = (locals[i], $"{obj}.{props[i]}");

        for (var i = 0; i < fields.Count; i++)
        {
            var f = fields[i];
            if (f.Kind is not ("array" or "bytes"))
                b.Read.Append($"{ind}{ScalarType(f)} {locals[i]} = default!;\n");
        }

        for (var i = 0; i < fields.Count; i++)
        {
            var f = fields[i];
            var p = props[i];
            var rc = f.When is null ? null : Cond(f.When, names, true);
            var wc = f.When is null ? null : Cond(f.When, names, false);
            var rin = rc is null ? ind : ind + "    ";
            if (rc is not null)
            {
                b.Read.Append($"{ind}if ({rc})\n{ind}{{\n");
                b.Write.Append($"{ind}if ({wc})\n{ind}{{\n");
            }

            switch (f.Kind)
            {
                case "bytes":
                    b.Props.Append($"    public byte[] {p} {{ get; set; }} = [];\n");
                    b.Read.Append($"{rin}{obj}.{p} = r.Bytes({f.Size});\n");
                    b.Write.Append($"{rin}w.Bytes({obj}.{p});\n");
                    break;
                case "array":
                    EmitArray(f, p, typePath, b, names, depth, rin, obj);
                    break;
                case "cname":
                    b.Props.Append($"    public CNameValue {p} {{ get; set; }}\n");
                    b.Read.Append($"{rin}{locals[i]} = r.CName(v);\n{rin}{obj}.{p} = {locals[i]};\n");
                    b.Write.Append($"{rin}w.CName({obj}.{p}, v);\n");
                    break;
                default:
                    var cs = Prim[f.Kind].Cs;
                    b.Props.Append($"    public {cs} {p} {{ get; set; }}{(cs == "string" ? " = \"\";" : "")}\n");
                    b.Read.Append($"{rin}{locals[i]} = {Prim[f.Kind].Read};\n{rin}{obj}.{p} = {locals[i]};\n");
                    b.Write.Append($"{rin}{string.Format(Prim[f.Kind].Write, $"{obj}.{p}")};\n");
                    break;
            }

            if (rc is not null)
            {
                b.Read.Append($"{ind}}}\n");
                b.Write.Append($"{ind}}}\n");
            }
        }
    }

    static string ScalarType(Field f) => f.Kind == "cname" ? "CNameValue" : Prim[f.Kind].Cs;

    void EmitArray(Field f, string p, string typePath, Block b, Dictionary<string, (string Read, string Write)> names, int depth, string ind, string obj)
    {
        var n = $"n{depth}_{p}";
        string countRead;
        string? countWrite = null;
        if (f.CountField is not null) countRead = $"(int){names[f.CountField].Read}";
        else if (int.TryParse(f.Count, out var literal)) countRead = literal.ToString();
        else
        {
            (countRead, countWrite) = f.Count switch
            {
                "u8" => ("r.U8()", "w.U8((byte){0});"),
                "u16" => ("r.U16()", "w.U16((ushort){0});"),
                "u32" => ("(int)r.U32()", "w.U32((uint){0});"),
                "varint" => ("r.Varint()", "w.Varint({0});"),
                _ => throw new InvalidOperationException($"array {p}: count type {f.Count}"),
            };
        }
        var arr = $"arr{depth}_{p}";
        var i = $"i{depth}";

        if (f.Element is not null)
        {
            var item = $"{p}Item";
            var path = $"{typePath}.{item}";
            var sub = new Block();
            var itemVar = $"item{depth + 1}";
            Members(f.Element, item, path, sub, names, depth + 1, ind + "        ", itemVar);
            b.Props.Append($"    public sealed class {item}\n    {{\n{sub.Props}    }}\n    public {item}[] {p} {{ get; set; }} = [];\n");
            b.Read.Append($"{ind}var {n} = {countRead};\n{ind}var {arr} = new {path}[{n}];\n{ind}for (var {i} = 0; {i} < {n}; {i}++)\n{ind}{{\n{ind}    var {itemVar} = new {path}();\n{sub.Read}{ind}    {arr}[{i}] = {itemVar};\n{ind}}}\n{ind}{obj}.{p} = {arr};\n");
            if (countWrite is not null) b.Write.Append($"{ind}{string.Format(countWrite, $"{obj}.{p}.Length")}\n");
            b.Write.Append($"{ind}foreach (var {itemVar} in {obj}.{p})\n{ind}{{\n{sub.Write}{ind}}}\n");
        }
        else if (f.ElementType is not null)
        {
            var (cs, rd, wr) = Prim[f.ElementType];
            b.Props.Append($"    public {cs}[] {p} {{ get; set; }} = [];\n");
            b.Read.Append($"{ind}var {n} = {countRead};\n{ind}var {arr} = new {cs}[{n}];\n{ind}for (var {i} = 0; {i} < {n}; {i}++) {arr}[{i}] = {rd};\n{ind}{obj}.{p} = {arr};\n");
            if (countWrite is not null) b.Write.Append($"{ind}{string.Format(countWrite, $"{obj}.{p}.Length")}\n");
            b.Write.Append($"{ind}foreach (var x{depth} in {obj}.{p}) {string.Format(wr, $"x{depth}")};\n");
        }
        else
        {
            b.Props.Append($"    public byte[] {p} {{ get; set; }} = [];\n");
            b.Read.Append($"{ind}var {n} = {countRead};\n{ind}{obj}.{p} = r.Bytes({n} * {f.ElementBytes});\n");
            if (countWrite is not null) b.Write.Append($"{ind}{string.Format(countWrite, $"{obj}.{p}.Length / {f.ElementBytes}")}\n");
            b.Write.Append($"{ind}w.Bytes({obj}.{p});\n");
        }
    }

    static string Cond(string when, Dictionary<string, (string Read, string Write)> names, bool read) =>
        Regex.Replace(Regex.Replace(Regex.Replace(when, @"(\w+)\s*(<=|<)\s*(\w+)\s*(<=|<)\s*(\w+)", "($1 $2 $3 && $3 $4 $5)"), @"(\w+) in \(([\d, ]+)\)", m => "(" + string.Join(" || ", m.Groups[2].Value.Split(',', StringSplitOptions.TrimEntries).Select(x => $"{m.Groups[1].Value} == {x}")) + ")"),
            "[A-Za-z_][A-Za-z0-9_]*", m => m.Value switch
        {
            "and" => "&&",
            "or" => "||",
            "v" or "a" => m.Value,
            var id => names.TryGetValue(id, out var x) ? (read ? x.Read : x.Write) : throw new InvalidOperationException($"unknown identifier '{id}' in when=\"{when}\""),
        });
}
